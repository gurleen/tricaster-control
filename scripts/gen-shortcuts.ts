/**
 * Generates src/lib/tricaster/shortcuts.gen.ts from config/shortcuts_cfg.xml.
 *
 *   pnpm gen:shortcuts [path/to/shortcuts_cfg.xml]
 *
 * Plain <shortcut>s become keys of `SimpleShortcuts`. Each <group> becomes a
 * prefix union + suffix interface, expanded at the type level with template
 * literal keys, so ~32k shortcut names stay type-checked without a 32k-line file.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { XMLParser } from 'fast-xml-parser'

const input = resolve(process.argv[2] ?? 'config/shortcuts_cfg.xml')
const output = resolve('src/lib/tricaster/shortcuts.gen.ts')

type Node = Record<string, unknown> & { ':@'?: Record<string, string> }

const parser = new XMLParser({
  preserveOrder: true,
  ignoreAttributes: false,
  attributeNamePrefix: '',
  commentPropName: '#comment',
  parseAttributeValue: false,
})

const tree = parser.parse(readFileSync(input, 'utf8')) as Node[]
const root = tree.find((n) => 'shortcuts' in n)
if (!root) throw new Error('No <shortcuts> root element found')

const tagOf = (n: Node) => Object.keys(n).find((k) => k !== ':@') ?? ''
const kids = (n: Node) => (n[tagOf(n)] as Node[]) ?? []
const attrs = (n: Node) => n[':@'] ?? {}
const commentText = (n: Node) =>
  kids(n)
    .map((c) => String(c['#text'] ?? ''))
    .join(' ')
    .trim()

const VALUE_TAGS = new Set(['void', 'bool', 'int', 'long', 'ulong', 'double', 'string', 'dynamic'])
const normTag = (t: string | undefined) => {
  const lower = t?.toLowerCase()
  return lower && VALUE_TAGS.has(lower) ? lower : 'unknown'
}

const ident = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))

function dictType(n: Node, tag: string): string | undefined {
  const dict = kids(n).find((c) => tagOf(c) === tag)
  if (!dict) return undefined
  const entries = kids(dict).filter((c) => tagOf(c) === 'entry')
  const fields = entries.map((e) => {
    const a = attrs(e)
    const dep = a.deprecated === 'true' ? '/** @deprecated */ ' : ''
    return `${dep}${ident(a.key)}?: '${normTag(a.type)}'`
  })
  return `{ ${fields.join('; ')} }`
}

function jsdoc(n: Node, indent: string): string {
  const a = attrs(n)
  const lines = kids(n)
    .filter((c) => tagOf(c) === '#comment')
    .map(commentText)
    .filter(Boolean)
    .map((l) => l.replace(/\*\//g, '* /').replace(/\s*\n\s*/g, ' '))
  if (a.deprecated === 'true') lines.push('@deprecated')
  if (a.undocumented === 'true') lines.push('@remarks Undocumented by Vizrt.')
  if (a.internal_only === 'true') lines.push('@remarks Internal only.')
  if (!lines.length) return ''
  return `${indent}/** ${lines.join(`\n${indent} * `)} */\n`
}

function spec(n: Node): string {
  const a = attrs(n)
  const d = dictType(n, 'shortcut_dictionary')
  const sd = dictType(n, 'state_dictionary')
  const raw = a.shortcut_type ?? a.type
  // A shortcut with only a dictionary and no declared type takes no plain value.
  const v = raw ? normTag(raw) : d ? 'void' : 'unknown'
  const parts = [`v: '${v}'`]
  if (a.state_type) parts.push(`s: '${normTag(a.state_type)}'`)
  if (d) parts.push(`d: ${d}`)
  if (sd) parts.push(`sd: ${sd}`)
  return `{ ${parts.join('; ')} }`
}

const simple = new Map<string, string>()
const groups: { label: string; prefixes: string[]; suffixes: Map<string, string> }[] = []
let lastComment = ''

for (const n of kids(root)) {
  const tag = tagOf(n)
  if (tag === '#comment') {
    lastComment = commentText(n)
    continue
  }
  if (tag === 'shortcut') {
    const name = attrs(n).name
    if (!simple.has(name)) simple.set(name, `${jsdoc(n, '  ')}  ${ident(name)}: ${spec(n)}`)
    // Nested <shortcut>s (seen once in the wild) are separate shortcuts.
    for (const c of kids(n).filter((c) => tagOf(c) === 'shortcut')) {
      const cn = attrs(c).name
      if (!simple.has(cn)) simple.set(cn, `${jsdoc(c, '  ')}  ${ident(cn)}: ${spec(c)}`)
    }
  } else if (tag === 'group') {
    const prefixes = kids(n)
      .filter((c) => tagOf(c) === 'prefix')
      .map((c) => attrs(c).name)
    const suffixes = new Map<string, string>()
    for (const s of kids(n).filter((c) => tagOf(c) === 'suffix')) {
      const name = attrs(s).name
      if (!suffixes.has(name)) suffixes.set(name, `${jsdoc(s, '  ')}  ${ident(name)}: ${spec(s)}`)
    }
    groups.push({ label: lastComment, prefixes: [...new Set(prefixes)], suffixes })
  }
  if (tag !== '#comment') lastComment = ''
}

const out: string[] = [
  '// AUTO-GENERATED by scripts/gen-shortcuts.ts from config/shortcuts_cfg.xml. Do not edit by hand.',
  '/* eslint-disable */',
  '// biome-ignore-all lint: generated file',
  '',
  "import type { ExpandGroup } from './spec'",
  '',
  'export interface SimpleShortcuts {',
  ...simple.values(),
  '}',
  '',
]

groups.forEach((g, i) => {
  out.push(
    `/** Group ${i}${g.label ? `: ${g.label.replace(/\*\//g, '')}` : ''} */`,
    `export const group${i}Prefixes = [${g.prefixes.map((p) => JSON.stringify(p)).join(', ')}] as const`,
    `export type Group${i}Prefix = (typeof group${i}Prefixes)[number]`,
    `export interface Group${i}Suffixes {`,
    ...g.suffixes.values(),
    '}',
    '',
  )
})

// Friendly aliases from the comment above each group, when the label is unique.
const pascal = (l: string) =>
  l
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase())
    .join('')
const labelCounts = new Map<string, number>()
for (const g of groups) {
  const k = pascal(g.label)
  if (k && /^[A-Z]/.test(k)) labelCounts.set(k, (labelCounts.get(k) ?? 0) + 1)
}
groups.forEach((g, i) => {
  const k = pascal(g.label)
  if (labelCounts.get(k) === 1) {
    out.push(
      `export const ${k[0].toLowerCase()}${k.slice(1)}Prefixes = group${i}Prefixes`,
      `export type ${k}Prefix = Group${i}Prefix`,
      `export type ${k}Suffixes = Group${i}Suffixes`,
    )
  }
})
out.push('')

out.push(
  '/** Every shortcut the TriCaster understands, keyed by full name. */',
  'export type ShortcutSpecs = SimpleShortcuts &',
  groups.map((_, i) => `  ExpandGroup<Group${i}Prefix, Group${i}Suffixes>`).join(' &\n'),
  '',
)

writeFileSync(output, out.join('\n'))

const total = simple.size + groups.reduce((sum, g) => sum + g.prefixes.length * g.suffixes.size, 0)
console.log(`Wrote ${output}: ${simple.size} shortcuts + ${groups.length} groups (~${total} names)`)
